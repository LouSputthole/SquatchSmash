/**
 * Which cue files actually exist, written to assets/sfx/index.json.
 *
 * The game fetches only what this lists. Without it the browser probes for
 * every cue in the manifest and logs a 404 for each one that has not been
 * recorded yet -- and a file that IS there but is not listed is simply never
 * fetched, so a delivered recording sits on disk while the game carries on
 * playing the procedural stand-in with nothing anywhere saying why.
 *
 * That last failure is why this lives in its own module rather than inside
 * the generator. `npm run sfx` rebuilds the index because it has just written
 * files; `npm run sfx:listen` rebuilds it because somebody has just dropped
 * hand-recorded mp3s into the folder, which is the only route the recorded-by-
 * a-human half of the audio ever takes. Both need the same rule, and the rule
 * drifting between two copies is the bug it exists to prevent.
 */
import fs from 'node:fs/promises';
import path from 'node:path';

/** Anything smaller than this is a placeholder or a truncated download. */
const MIN_BYTES = 512;

/**
 * @param {string} sfxDir absolute path to assets/sfx
 * @returns {Promise<string[]>} the filenames written to the index
 */
export async function writeIndex(sfxDir) {
  const entries = await fs.readdir(sfxDir);
  const files = [];
  for (const name of entries) {
    if (!/\.(mp3|ogg|wav|m4a)$/i.test(name)) continue;
    const st = await fs.stat(path.join(sfxDir, name));
    if (st.size > MIN_BYTES) files.push(name);
  }
  files.sort();
  await fs.writeFile(path.join(sfxDir, 'index.json'), JSON.stringify({
    _comment: 'Generated by tools/sfx-index-json.mjs, via `npm run sfx` or `npm run sfx:listen`. Lists the cue files present in this folder.',
    files,
  }, null, 2) + '\n');
  return files;
}
